"""Validated, cached OSM road geometry for explicitly simulated demo routes.

GeoJSON uses [longitude, latitude]; API/map coordinates use named latitude/longitude.
The cache was generated by scripts/build_demo_geometry.py. It is not an official
BakuBus route shape.
"""
from bisect import bisect_right
from dataclasses import dataclass
from functools import lru_cache
import json
from math import asin, atan2, cos, degrees, radians, sin, sqrt
from pathlib import Path

GEOMETRY_DIR = Path(__file__).resolve().parents[2] / "data" / "geometry"
BAKU_BOUNDS = (40.20, 40.60, 49.50, 50.20)

def valid_baku(lat: float, lon: float) -> bool:
    return BAKU_BOUNDS[0] <= lat <= BAKU_BOUNDS[1] and BAKU_BOUNDS[2] <= lon <= BAKU_BOUNDS[3]

def geojson_to_latlon(coordinate):
    if not isinstance(coordinate, (list, tuple)) or len(coordinate) != 2:
        raise ValueError("GeoJSON coordinate must be [longitude, latitude]")
    lon, lat = map(float, coordinate)
    if not valid_baku(lat, lon):
        raise ValueError("Coordinate outside Baku bounds or reversed")
    return lat, lon

def latlon_to_geojson(lat: float, lon: float) -> list[float]:
    if not valid_baku(lat, lon):
        raise ValueError("Coordinate outside Baku bounds or reversed")
    return [lon, lat]

def distance_m(a, b) -> float:
    lat1, lon1 = geojson_to_latlon(a)
    lat2, lon2 = geojson_to_latlon(b)
    x = sin(radians(lat2-lat1)/2)**2 + cos(radians(lat1))*cos(radians(lat2))*sin(radians(lon2-lon1)/2)**2
    return 6371000 * 2 * asin(min(1, sqrt(x)))

def bearing(a, b) -> float:
    lat1, lon1 = map(radians, geojson_to_latlon(a))
    lat2, lon2 = map(radians, geojson_to_latlon(b))
    dlon = lon2-lon1
    return (degrees(atan2(sin(dlon)*cos(lat2), cos(lat1)*sin(lat2)-sin(lat1)*cos(lat2)*cos(dlon)))+360)%360

@dataclass(frozen=True)
class RoadPath:
    route_id: str
    direction_id: str
    coordinates: tuple[tuple[float, float], ...]
    cumulative_m: tuple[float, ...]
    stop_distances_m: tuple[float, ...]
    stop_coordinates: tuple[tuple[float, float], ...]
    feature: dict

    @property
    def length_m(self) -> float:
        return self.cumulative_m[-1]

    def position(self, distance_along_m: float):
        distance_along_m = distance_along_m % self.length_m
        index = min(bisect_right(self.cumulative_m, distance_along_m)-1, len(self.coordinates)-2)
        left, right = self.cumulative_m[index:index+2]
        fraction = (distance_along_m-left)/(right-left)
        a, b = self.coordinates[index:index+2]
        lon = a[0]+(b[0]-a[0])*fraction
        lat = a[1]+(b[1]-a[1])*fraction
        return lat, lon, bearing(a,b), index, fraction

def validate_feature(feature: dict) -> RoadPath:
    if feature.get("type") != "Feature" or feature.get("geometry", {}).get("type") != "LineString":
        raise ValueError("LineString GeoJSON required")
    props = feature.get("properties", {})
    if props.get("geometry_source") != "OSM_DERIVED" or props.get("provider") != "OSRM":
        raise ValueError("Road provenance missing")
    coords = feature["geometry"]["coordinates"]
    if len(coords) < 3:
        raise ValueError("Route has too few vertices")
    cumulative = [0.0]
    previous = None
    for item in coords:
        geojson_to_latlon(item)
        if previous is not None:
            step = distance_m(previous, item)
            if not 0 < step <= 500:
                raise ValueError("Route has a gap, repeated vertex or implausible jump")
            cumulative.append(cumulative[-1]+step)
        previous = item
    stop_distances = props.get("stop_distances_m", [])
    stop_coordinates = props.get("stop_coordinates", [])
    if len(stop_distances) < 2 or len(stop_distances) != len(stop_coordinates):
        raise ValueError("Stop offsets missing")
    if abs(stop_distances[0]) > 0.01 or any(a >= b for a,b in zip(stop_distances, stop_distances[1:])):
        raise ValueError("Stop offsets out of order")
    if stop_distances[-1] >= cumulative[-1]:
        raise ValueError("Closing leg missing")
    for item in stop_coordinates:
        geojson_to_latlon(item)
    if not props.get("route_id", "").isalnum() or not props.get("direction_id", "").isalnum():
        raise ValueError("Route or direction identifier invalid")
    path = RoadPath(
        route_id=props["route_id"], direction_id=props["direction_id"],
        coordinates=tuple(tuple(map(float, point)) for point in coords),
        cumulative_m=tuple(cumulative), stop_distances_m=tuple(map(float, stop_distances)),
        stop_coordinates=tuple(tuple(map(float, point)) for point in stop_coordinates),
        feature=feature,
    )
    for offset, coordinate in zip(path.stop_distances_m, path.stop_coordinates):
        lat, lon, _, _, _ = path.position(offset)
        if distance_m([lon, lat], coordinate) > 3:
            raise ValueError("Stop offset is not on the road path")
    return path

@lru_cache(maxsize=16)
def road_path(route_id: str, direction_id: str = "LOOP") -> RoadPath | None:
    if not route_id.isalnum() or not direction_id.isalnum():
        return None
    file = GEOMETRY_DIR / f"{route_id}-{direction_id}.geojson"
    try:
        path = validate_feature(json.loads(file.read_text(encoding="utf-8")))
        return path if path.route_id == route_id and path.direction_id == direction_id else None
    except (OSError, ValueError, KeyError, TypeError):
        return None
